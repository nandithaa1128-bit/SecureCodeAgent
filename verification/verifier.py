"""
Verification Agent (Member 3: Patch Verification)
==================================================
SecureCodeAgent Framework

This module evaluates proposed security patches generated by the Self-Repair Agent.
It guarantees that AI-generated code fixes are never trusted blindly by performing:
1. Python Syntax Validation (ast.parse)
2. Security Rescanning (Bandit static analysis)
3. Before-and-After Security Differential Analysis
4. Safe Automated Functional Testing (pytest execution with isolation & timeout)
5. Structured Verification Report Generation
"""

import ast
import json
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional


def check_syntax(source_code: str) -> Dict[str, Any]:
    """
    Check if the given Python source code is syntactically valid.

    Args:
        source_code (str): The Python code string to inspect.

    Returns:
        dict: Status ('PASSED' or 'FAILED'), line number, and error details.
    """
    if not source_code or not source_code.strip():
        return {
            "status": "FAILED",
            "passed": False,
            "error": "Source code is empty.",
            "line": None,
        }

    try:
        ast.parse(source_code)
        return {
            "status": "PASSED",
            "passed": True,
            "error": None,
            "line": None,
        }
    except SyntaxError as exc:
        return {
            "status": "FAILED",
            "passed": False,
            "error": f"{exc.msg} (line {exc.lineno})",
            "line": exc.lineno,
        }


def scan_file_security(file_path: str) -> Dict[str, Any]:
    """
    Run security static analysis on a target Python file using Bandit.

    Gracefully reuses Member 1's detector (detection.detector.scan_file)
    if available, otherwise falls back to running Bandit directly.

    Args:
        file_path (str): Path to the Python file to scan.

    Returns:
        dict: Scan outcome, total issues count, and list of normalized findings.
    """
    target = Path(file_path).resolve()
    if not target.is_file():
        return {
            "status": "ERROR",
            "error": f"File not found: {target}",
            "findings": [],
            "total_issues": 0,
        }

    # Try importing detector from Member 1 if present and functional
    try:
        from detection.detector import scan_file as detector_scan  # type: ignore

        report = detector_scan(str(target))
        if isinstance(report, dict) and "findings" in report:
            return {
                "status": "SUCCESS",
                "findings": report.get("findings", []),
                "total_issues": report.get("total_issues", len(report.get("findings", []))),
                "error": None,
            }
    except Exception:
        # Fall back to internal Bandit execution if Member 1 module is not yet ready
        pass

    # Direct Bandit runner fallback
    try:
        cmd = [
            sys.executable,
            "-m",
            "bandit",
            "-f",
            "json",
            "-q",
            str(target),
        ]
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=45,
            check=False,
        )

        # Bandit returns 0 (no issues) or 1 (issues found). Other codes mean an execution error.
        if result.returncode not in (0, 1):
            return {
                "status": "ERROR",
                "error": f"Bandit execution failed: {result.stderr or result.stdout}",
                "findings": [],
                "total_issues": 0,
            }

        report_data = json.loads(result.stdout or "{}")
        raw_results = report_data.get("results", [])

        normalized_findings = []
        for issue in raw_results:
            normalized_findings.append(
                {
                    "test_id": issue.get("test_id"),
                    "issue": issue.get("issue_text"),
                    "line_number": issue.get("line_number"),
                    "severity": issue.get("issue_severity"),
                    "confidence": issue.get("issue_confidence"),
                }
            )

        return {
            "status": "SUCCESS",
            "findings": normalized_findings,
            "total_issues": len(normalized_findings),
            "error": None,
        }
    except subprocess.TimeoutExpired:
        return {
            "status": "ERROR",
            "error": "Bandit security scan timed out after 45 seconds.",
            "findings": [],
            "total_issues": 0,
        }
    except Exception as exc:
        return {
            "status": "ERROR",
            "error": f"Security scan failed with exception: {exc}",
            "findings": [],
            "total_issues": 0,
        }


def compare_security_findings(
    original_findings: List[Dict[str, Any]],
    patched_findings: List[Dict[str, Any]],
) -> Dict[str, Any]:
    """
    Compare security scan findings before and after the patch is applied.

    Categorizes findings into:
    - resolved: Vulnerabilities present originally that are eliminated in the patch.
    - unresolved: Vulnerabilities present originally that persist in the patch.
    - new_issues: New vulnerabilities introduced into the patched code by the fix.

    Args:
        original_findings (list): Security issues identified in the original code.
        patched_findings (list): Security issues identified in the patched code.

    Returns:
        dict: Differential security metrics and classified finding lists.
    """
    orig_keys = {
        (f.get("test_id"), f.get("issue")) for f in original_findings
    }
    patch_keys = {
        (f.get("test_id"), f.get("issue")) for f in patched_findings
    }

    resolved = [
        f for f in original_findings
        if (f.get("test_id"), f.get("issue")) not in patch_keys
    ]

    unresolved = [
        f for f in original_findings
        if (f.get("test_id"), f.get("issue")) in patch_keys
    ]

    new_issues = [
        f for f in patched_findings
        if (f.get("test_id"), f.get("issue")) not in orig_keys
    ]

    orig_count = len(original_findings)
    patch_count = len(patched_findings)
    resolution_rate = (
        (len(resolved) / orig_count * 100.0) if orig_count > 0 else 100.0
    )

    return {
        "original_count": orig_count,
        "patched_count": patch_count,
        "resolved_count": len(resolved),
        "unresolved_count": len(unresolved),
        "new_issues_count": len(new_issues),
        "resolution_rate_percent": round(resolution_rate, 2),
        "resolved_findings": resolved,
        "unresolved_findings": unresolved,
        "new_findings": new_issues,
        "is_completely_clean": patch_count == 0,
    }


def run_functional_tests(
    test_file_path: Optional[str] = None,
    timeout: int = 30,
) -> Dict[str, Any]:
    """
    Execute automated functional tests using pytest in a controlled subprocess.

    Requirements:
    - Runs in an isolated subprocess to protect against long hangs or side-effects.
    - Explicitly reports SKIPPED when no test file is provided, rather than
      falsely claiming tests passed.

    Args:
        test_file_path (str, optional): Path to the pytest test suite file.
        timeout (int): Maximum test execution time in seconds.

    Returns:
        dict: Test execution status ('PASSED', 'FAILED', or 'SKIPPED') and output.
    """
    if not test_file_path or not os.path.exists(test_file_path):
        return {
            "status": "SKIPPED",
            "passed": None,
            "message": "No automated test suite provided; functional correctness unverified.",
            "output": "",
        }

    try:
        result = subprocess.run(
            [
                sys.executable,
                "-m",
                "pytest",
                str(Path(test_file_path).resolve()),
                "-q",
                "--tb=short",
            ],
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )

        passed = (result.returncode == 0)
        return {
            "status": "PASSED" if passed else "FAILED",
            "passed": passed,
            "message": "Pytest suite completed." if passed else "Pytest suite failed.",
            "output": (result.stdout + "\n" + result.stderr).strip(),
            "returncode": result.returncode,
        }
    except subprocess.TimeoutExpired:
        return {
            "status": "FAILED",
            "passed": False,
            "message": f"Tests timed out after {timeout} seconds.",
            "output": "",
            "returncode": -1,
        }
    except Exception as exc:
        return {
            "status": "FAILED",
            "passed": False,
            "message": f"Failed to execute tests: {exc}",
            "output": "",
            "returncode": -1,
        }


def determine_verdict(
    syntax_result: Dict[str, Any],
    diff_result: Dict[str, Any],
    test_result: Dict[str, Any],
) -> Dict[str, str]:
    """
    Determine the overall verification verdict based on all checks.

    Verdict Levels:
    - VERIFIED_SECURE: Syntax is valid, all original security issues resolved,
      no new security issues introduced, and functional tests passed (or were cleanly skipped).
    - PARTIALLY_VERIFIED: Syntax is valid, some issues were resolved, but unresolved issues remain,
      or functional tests have not been executed.
    - VERIFICATION_FAILED: Syntax errors detected, new vulnerabilities introduced,
      zero issues resolved, or functional tests failed.

    Returns:
        dict: 'verdict' code and human-readable 'summary'.
    """
    if not syntax_result.get("passed", False):
        return {
            "verdict": "VERIFICATION_FAILED",
            "summary": f"Patch rejected: Syntax error detected -> {syntax_result.get('error')}",
        }

    if test_result.get("passed") is False:
        return {
            "verdict": "VERIFICATION_FAILED",
            "summary": "Patch rejected: Functional tests failed, breaking existing application behavior.",
        }

    new_issues = diff_result.get("new_issues_count", 0)
    unresolved = diff_result.get("unresolved_count", 0)
    resolved = diff_result.get("resolved_count", 0)
    orig_count = diff_result.get("original_count", 0)

    if new_issues > 0:
        return {
            "verdict": "VERIFICATION_FAILED",
            "summary": f"Patch rejected: Fix introduced {new_issues} new security vulnerability/vulnerabilities.",
        }

    if orig_count > 0 and resolved == 0:
        return {
            "verdict": "VERIFICATION_FAILED",
            "summary": "Patch rejected: None of the reported vulnerabilities were resolved.",
        }

    if unresolved > 0:
        return {
            "verdict": "PARTIALLY_VERIFIED",
            "summary": f"Patch partially verified: {resolved} issue(s) resolved, but {unresolved} issue(s) still remain.",
        }

    # All security issues resolved and 0 new issues
    if test_result.get("status") == "PASSED":
        return {
            "verdict": "VERIFIED_SECURE",
            "summary": "Patch successfully verified: Valid syntax, all security issues resolved, zero regressions, and functional tests passed.",
        }

    # All security issues resolved, tests skipped
    return {
        "verdict": "VERIFIED_SECURE",
        "summary": "Patch verified for security: Valid syntax, zero remaining vulnerabilities, and zero new issues. (Note: functional tests were skipped).",
    }


def verify_patch(
    original_file: str,
    patched_file: str,
    test_file: Optional[str] = None,
    original_findings: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Main verification pipeline for SecureCodeAgent Member 3.

    Validates that:
    1. The original and patched files exist and are distinct (no overwrites).
    2. The patched code has valid Python syntax.
    3. Security scan on patched code is performed and compared with baseline.
    4. Safe automated tests are executed if a test suite is provided.
    5. A comprehensive verification report is produced.

    Args:
        original_file (str): Path to original vulnerable Python file.
        patched_file (str): Path to proposed patched Python file.
        test_file (str, optional): Path to test suite for functional testing.
        original_findings (list, optional): Pre-existing findings from Member 1.
                                            If None, original_file will be scanned automatically.

    Returns:
        dict: Complete structured verification report.
    """
    orig_path = Path(original_file).resolve()
    patch_path = Path(patched_file).resolve()

    # Safety Check: Guard against file collisions
    if orig_path == patch_path:
        raise ValueError(
            "Original file and patched file paths must be different. "
            "Verification refuses to evaluate a patch that overwrites the original source."
        )

    if not orig_path.is_file():
        raise FileNotFoundError(f"Original source file not found: {orig_path}")

    if not patch_path.is_file():
        raise FileNotFoundError(f"Patched source file not found: {patch_path}")

    patched_code = patch_path.read_text(encoding="utf-8")

    # Step 1: Syntax Validation
    syntax_result = check_syntax(patched_code)

    # Step 2: Baseline security findings for original file
    if original_findings is None:
        orig_scan = scan_file_security(str(orig_path))
        orig_findings = orig_scan.get("findings", [])
    else:
        orig_findings = original_findings

    # Step 3: Security rescan of patched file
    # If syntax is completely broken, we skip running bandit as it will fail on invalid AST
    if syntax_result["passed"]:
        patch_scan = scan_file_security(str(patch_path))
        patch_findings = patch_scan.get("findings", [])
    else:
        patch_scan = {
            "status": "SKIPPED",
            "findings": [],
            "total_issues": 0,
            "error": "Security rescan skipped due to invalid syntax.",
        }
        patch_findings = []

    # Step 4: Differential security comparison
    diff_result = compare_security_findings(orig_findings, patch_findings)

    # Step 5: Functional testing
    if syntax_result["passed"]:
        test_result = run_functional_tests(test_file)
    else:
        test_result = {
            "status": "SKIPPED",
            "passed": False,
            "message": "Functional tests skipped due to syntax errors.",
            "output": "",
        }

    # Step 6: Determine Final Verdict
    verdict_info = determine_verdict(syntax_result, diff_result, test_result)

    report = {
        "timestamp": datetime.now().isoformat(),
        "files": {
            "original_file": str(orig_path),
            "patched_file": str(patch_path),
            "test_file": str(Path(test_file).resolve()) if test_file else None,
        },
        "verdict": verdict_info["verdict"],
        "summary": verdict_info["summary"],
        "checks": {
            "syntax": syntax_result,
            "security_rescan": {
                "scan_status": patch_scan.get("status"),
                "comparison": diff_result,
            },
            "functional_tests": test_result,
        },
    }

    return report


def format_report_markdown(report: Dict[str, Any]) -> str:
    """Format a verification report dictionary into a readable Markdown document."""
    files = report["files"]
    checks = report["checks"]
    syntax = checks["syntax"]
    sec = checks["security_rescan"]["comparison"]
    tests = checks["functional_tests"]

    verdict_badge = {
        "VERIFIED_SECURE": "✅ VERIFIED SECURE",
        "PARTIALLY_VERIFIED": "⚠️ PARTIALLY VERIFIED",
        "VERIFICATION_FAILED": "❌ VERIFICATION FAILED",
    }.get(report["verdict"], report["verdict"])

    lines = [
        "# 🛡️ SecureCodeAgent - Patch Verification Report",
        "",
        f"**Timestamp:** `{report['timestamp']}`  ",
        f"**Original File:** `{files['original_file']}`  ",
        f"**Patched File:** `{files['patched_file']}`  ",
        "",
        f"## Verdict: {verdict_badge}",
        f"> {report['summary']}",
        "",
        "---",
        "### 1. Syntax Check",
        f"- **Status:** {'✅ PASSED' if syntax['passed'] else '❌ FAILED'}",
    ]

    if not syntax["passed"]:
        lines.append(f"- **Error:** `{syntax['error']}`")

    lines.extend([
        "",
        "### 2. Security Rescan & Differential Analysis",
        f"- **Baseline Vulnerabilities:** {sec['original_count']}",
        f"- **Remaining Vulnerabilities:** {sec['patched_count']}",
        f"- **Resolved Vulnerabilities:** {sec['resolved_count']}",
        f"- **Newly Introduced Issues:** {sec['new_issues_count']}",
        f"- **Resolution Rate:** `{sec['resolution_rate_percent']}%`",
    ])

    if sec["resolved_findings"]:
        lines.append("\n**Resolved Issues:**")
        for f in sec["resolved_findings"]:
            lines.append(f"  - `[{f.get('test_id')}]` {f.get('issue')} (Line {f.get('line_number')})")

    if sec["unresolved_findings"]:
        lines.append("\n**Unresolved Issues:**")
        for f in sec["unresolved_findings"]:
            lines.append(f"  - `[{f.get('test_id')}]` {f.get('issue')} (Line {f.get('line_number')})")

    if sec["new_findings"]:
        lines.append("\n**⚠️ Newly Introduced Issues:**")
        for f in sec["new_findings"]:
            lines.append(f"  - `[{f.get('test_id')}]` {f.get('issue')} (Line {f.get('line_number')})")

    lines.extend([
        "",
        "### 3. Functional Automated Tests",
        f"- **Status:** `{tests['status']}`",
        f"- **Details:** {tests.get('message', 'N/A')}",
    ])

    if tests.get("output"):
        lines.append(f"```\n{tests['output']}\n```")

    lines.append("\n---")
    return "\n".join(lines)


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(
        description="Verify an AI-generated security patch against syntax, security, and tests."
    )
    parser.add_argument("original_file", help="Path to original vulnerable file")
    parser.add_argument("patched_file", help="Path to proposed patched file")
    parser.add_argument("--test-file", default=None, help="Optional test suite file")
    parser.add_argument("--json", action="store_true", help="Output raw JSON report")
    parser.add_argument("--output-report", default=None, help="Save report to file path")

    args = parser.parse_args()

    try:
        report_data = verify_patch(
            original_file=args.original_file,
            patched_file=args.patched_file,
            test_file=args.test_file,
        )

        if args.json:
            output_str = json.dumps(report_data, indent=2)
        else:
            output_str = format_report_markdown(report_data)

        print(output_str)

        if args.output_report:
            out_path = Path(args.output_report).resolve()
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(output_str, encoding="utf-8")
            print(f"\nReport saved to: {out_path}")

        # Exit code: 0 if verified, 1 if failed or partial
        sys.exit(0 if report_data["verdict"] == "VERIFIED_SECURE" else 1)

    except Exception as error:
        print(f"Verification Error: {error}", file=sys.stderr)
        sys.exit(2)
